LEVELS = [WINDMILL_GREEN, OVER_THE_HEDGES, CHIMNEY_RUN, THE_BELFRY, ICE_STEPS, FROZEN_BELLS, HUSH_CLOUDS, THE_LAST_BELFRY]


def write():
    text = RULES.read_text(encoding="utf-8")
    start, stop = text.index(BEGIN) + len(BEGIN), text.index(END)
    out = ["export const LEVELS = [\n"]
    for level in LEVELS:
        out.append("    { name: %s, world: %d, seconds: %d, rows: [\n" % (json.dumps(level["name"]), level["world"], level["seconds"]))
        out.extend("        %s,\n" % json.dumps(row) for row in level["rows"])
        out.append("    ] },\n")
    out.append("]\n")
    RULES.write_text(text[:start] + "".join(out) + text[stop:], encoding="utf-8", newline="\n")
    return LEVELS


if __name__ == "__main__":
    for level in write():
        print(level["name"], len(level["rows"][0]), "by", len(level["rows"]))
