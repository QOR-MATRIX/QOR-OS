"""Lays out Bellwick's eight levels and writes them between the markers in logic/rules.mjs, the same bytes every time,
because the rules decide what can be stood on and ARQADE's service replays them. make_assets.py builds their models from
the same lists: python make_levels.py

A level is hand-laid in set pieces read left to right. Each piece's rows are written from its highest thing down to its
floor line, the last row, and the floor line's marks run on down to the level's foot, so a piece says nothing of how deep
the level is. A blank column in the floor line is a pit.

  .  nothing                       #  ground             I  ice                =  a plank, stood on from above
  B  brick                         Q  a note block       R  a rich block       P  a power block      L  a life block
  H  a hush block, there when rung T  thorns             J  a spring           K  a mid-way bell     G  the Great Bell
  o  a note                        S  a silver bell      @  where Tam starts
  a  mumble   b  hushling   c  thistle   d  flit   e  boing   f  gourd   g  icicle   X  Old Muffle
  M  a platform three tiles wide that moves along its row to the ! on it
  V  the same, moving along its column to the ! in it
  F  a platform two tiles wide that falls when stood on
  D  a door, and E the door it opens on (the first D with the first E, and so on)
"""
import json
import pathlib
import textwrap

HERE = pathlib.Path(__file__).parent
RULES = HERE / "logic" / "rules.mjs"
BEGIN = "// LEVELS BEGIN\n"
END = "// LEVELS END\n"

KNOWN = set(".#I=BQRPLHTJKGoS@abcdefgXMVF!DE")
# Tiles the floor line may run down to the foot.
FLOORS = set("#I")


def piece(rows):
    """A set piece's rows, from a triple-quoted block, every one as wide as the widest."""
    lines = textwrap.dedent(rows).strip("\n").split("\n")
    width = max(len(line) for line in lines)
    assert all(len(line) == width for line in lines), [line for line in lines if len(line) != width]
    return lines


def to_wall(p):
    """The piece with the Great Bell, ending where the wall behind it stands, twelve tiles past the bell (the rules'
    WALL_AFTER_BELL): trimmed, or its floor carried on."""
    at = next(row.index("G") for row in p if "G" in row)
    width = at + 12
    return [row[:width].ljust(width, row[-1] if n == len(p) - 1 else ".") for n, row in enumerate(p)]


def room(rows):
    """A secret room, its wall toward the level three tiles thick, so it is not seen from outside."""
    return ["##" + row for row in piece(rows)]


def lay(name, world, seconds, depth, pieces):
    """A level: its pieces side by side, each one's floor line `depth` rows above its foot, and the rows above as tall as
    the tallest piece needs, with two clear rows at the top."""
    height = max(len(p) for p in pieces) + 2
    total = height + depth
    columns = [[] for _ in range(total)]
    for p in pieces:
        width = len(p[0])
        blank = height - len(p)
        for r in range(total):
            if r < blank:
                columns[r].append("." * width)
            elif r < height:
                columns[r].append(p[r - blank])
            else:
                columns[r].append("".join(c if c in FLOORS else "." for c in p[-1]))
    rows = ["".join(row) for row in columns]
    check(name, rows)
    return {"name": name, "world": world, "seconds": seconds, "rows": rows}


def check(name, rows):
    cols = len(rows[0])
    text = "".join(rows)
    assert all(len(row) == cols for row in rows), name
    assert set(text) <= KNOWN, (name, set(text) - KNOWN)
    assert text.count("@") == 1, (name, "a level starts once")
    assert text.count("S") == 3, (name, "three silver bells", text.count("S"))
    assert text.count("G") + text.count("X") == 1, (name, "it ends once")
    assert text.count("D") == text.count("E"), (name, "doors in pairs")
    for r, row in enumerate(rows):
        for c, tile in enumerate(row):
            if tile == "M":
                assert "!" in row[c + 1:], (name, "a platform with nowhere to go", r, c)
            elif tile == "V":
                assert any(rows[n][c] == "!" for n in range(len(rows)) if n != r), (name, "a lift with nowhere to go", r, c)


