function rotl(x, k) {
    return ((x << k) | (x >>> (32 - k))) >>> 0
}

/** The four words of xoshiro128**'s state, from a seed, by splitmix32. */
function seeded(seed) {
    let s = seed >>> 0
    const state = []
    for (let i = 0; i < 4; i++) {
        s = (s + 0x9e3779b9) >>> 0
        let z = s
        z = Math.imul(z ^ (z >>> 16), 0x85ebca6b) >>> 0
        z = Math.imul(z ^ (z >>> 13), 0xc2b2ae35) >>> 0
        state.push((z ^ (z >>> 16)) >>> 0)
    }
    if (state.every((w) => w === 0))
        state[0] = 1
    return state
}

/** The next 32-bit word, xoshiro128**. */
function nextWord(state) {
    const result = Math.imul(rotl(Math.imul(state[1], 5) >>> 0, 7), 9) >>> 0
    const t = (state[1] << 9) >>> 0
    state[2] = (state[2] ^ state[0]) >>> 0
    state[3] = (state[3] ^ state[1]) >>> 0
    state[1] = (state[1] ^ state[2]) >>> 0
    state[0] = (state[0] ^ state[3]) >>> 0
    state[2] = (state[2] ^ t) >>> 0
    state[3] = rotl(state[3], 11)
    return result
}

/** A whole number from `low` to `high`, both included. */
function between(state, low, high) {
    return low + Math.floor((nextWord(state) / 4294967296) * (high - low + 1))
}

// ── The level ───────────────────────────────────────────────────────────────────────────────────────────────────────

/** The tile at a column and row as it stands now. Past a level's sides is wall, and past its foot is air. */
export function tileAt(game, c, r) {
    const map = MAPS[game.level]
    if (c < 0 || c >= map.cols)
        return "#"
    if (r < 0 || r >= map.rows)
        return "."
    const changed = game.changed[r * map.cols + c]
    return changed !== undefined ? changed : map.tiles[r].charAt(c)
}

/** Whether a tile stops a body from every side. A hush block does while it is awake. */
export function solidAt(game, c, r) {
    const tile = tileAt(game, c, r)
    if (tile === "H")
        return game.awake[r * MAPS[game.level].cols + c] !== undefined
    return tile !== "." && tile !== "=" && tile !== "T"
}

/** Whether a body falling onto a tile stands on it. */
function standsOn(game, c, r) {
    return solidAt(game, c, r) || tileAt(game, c, r) === "="
}

/** Whether a body's feet at (x, y), half its width across, are over something to stand on, a step down. */
function footing(game, x, y, w) {
    const r = Math.floor((y + 1) / TILE)
    for (let c = Math.floor((x - w + 1) / TILE); c <= Math.floor((x + w - 1) / TILE); c++)
        if (standsOn(game, c, r))
            return true
    return false
}

function say(game, what, x, y, more) {
    game.said.push(Object.assign({ what: what, x: x, y: y }, more || {}))
}

function newHero(c, r) {
    return { x: (c + 0.5) * TILE, y: (r + 1) * TILE, vx: 0, vy: 0, before: (r + 1) * TILE, ground: false, facing: 1, form: SMALL,
             hurt: 0, dying: 0, coyote: 0, buffer: 0, lifted: false, slam: 0, on: -1, ringing: 0, ringCool: 0, skid: false,
             gliding: false, hold: 0, chain: 0,
             held: { left: false, right: false, up: false, down: false, jump: false, run: false, ring: false },
             ask: { ring: false, up: false, down: false } }
}

function spawn(game, kind, x, y, face) {
    const e = KINDS[kind]
    const made = { id: game.made, kind: kind, x: x, y: y, vx: 0, vy: 0, face: face, act: "go", timer: 0, stun: 0, ground: false,
                   homeX: x, homeY: y, phase: between(game.random, 0, 119) }
    game.made += 1
    if (kind === MUFFLE) {
        made.hits = MAPS[game.level].world === 3 ? 5 : 3
        made.most = made.hits
        made.act = "prowl"
        made.timer = PROWL_STEPS
        made.deaf = 0
    } else if (kind === ICICLE) {
        made.act = "hang"
    } else if (kind === BOING) {
        made.timer = 40 + made.phase
    } else if (kind === GOURD) {
        made.timer = 60 + made.phase
    }
    made.vx = kind === FLIT ? e.speed : 0
    game.enemies.push(made)
}

/** What a level holds at its start or a waking: everything that moves, back where it began. What was broken or rung out of
 * a block, and what was picked up, stays so: a life spent is not more notes. */
function stock(game) {
    const map = MAPS[game.level]
    game.enemies = []
    game.shots = []
    game.items = []
    game.awake = {}
    for (const s of map.spawns) {
        const kind = KINDS[s.kind]
        const x = (s.c + 0.5) * TILE
        const y = s.kind === ICICLE ? s.r * TILE + kind.h : s.kind === FLIT ? (s.r + 1) * TILE - 6 : (s.r + 1) * TILE
        spawn(game, s.kind, x, y, -1)
    }
    game.platforms = map.platforms.map((p, n) => {
        const span = Math.abs(p.to[0] + p.to[1]) * TILE
        const period = 2 * Math.floor(span / PLATFORM_SPEED + 0.5)
        return { id: n, what: p.what, w: p.w * TILE, ax: p.c * TILE, ay: p.r * TILE, x: p.c * TILE, y: p.r * TILE, dx: 0, dy: 0,
                 period: period, t: period > 0 ? between(game.random, 0, period - 1) : 0, act: "still", timer: 0, vy: 0,
                 sx: p.to[0] > 0 ? 1 : p.to[0] < 0 ? -1 : 0, sy: p.to[1] > 0 ? 1 : p.to[1] < 0 ? -1 : 0 }
    })
    for (const p of game.platforms)
        if (p.what === "mover")
            carryAlong(p)
}

/** A level entered: its clock, its stock and Tam at its start. */
export function enter(game, n) {
    game.level = n
    const map = MAPS[n]
    game.changed = {}
    game.rich = {}
    game.got = map.notes.map(() => 0)
    game.silverGot = map.silver.map(() => 0)
    game.check = -1
    game.time = map.seconds * 60
    game.clearing = 0
    const held = game.hero ? game.hero.held : null
    const form = game.hero ? game.hero.form : SMALL
    game.hero = newHero(map.start[0], map.start[1])
    game.hero.form = form
    if (held)
        game.hero.held = held
    stock(game)
}

function begin(game) {
    game.hero = null
    game.lives = LIVES
    game.notes = 0
    game.toLife = 0
    game.lastNote = -NOTE_CHAIN
    game.noteRun = 0
    game.score = 0
    game.silver = 0
    game.kills = 0
    game.falls = 0
    game.levels = 0
    game.steps = 0
    game.made = 0
    game.won = false
    game.said = []
    enter(game, 0)
    game.phase = "playing"
}

/** A game on its title screen, from `seed`. */
export function create(seed) {
    const game = { seed: seed >>> 0, random: seeded(seed), phase: "title", runs: 0 }
    begin(game)
    game.phase = "title"
    return game
}

function noAsks(h) {
    h.ask = { ring: false, up: false, down: false }
    h.buffer = 0
}

/** A screen button pressed: the phase's. */
export function click(game, button) {
    if (button === "Play" && game.phase === "title")
        game.phase = "playing"
    else if (button === "Play again" && game.phase === "over") {
        game.runs += 1
        begin(game)
    } else if (button === "Resume" && game.phase === "paused")
        game.phase = "playing"
    else
        return
    // What was pressed on a screen, the title's or the pause's, does nothing once play starts.
    noAsks(game.hero)
}

/** An action pressed. Moving and running are held whatever the phase, so a key held through a pause still counts after it; a
 * press of the others is kept for the next step, so a press let go before it still counts. */
export function press(game, action) {
    const h = game.hero
    if (action in h.held)
        h.held[action] = true
    if (action === "jump")
        h.buffer = BUFFER
    else if (action in h.ask)
        h.ask[action] = true
    else if (action === "pause" && game.phase === "playing")
        game.phase = "paused"
    else if (action === "pause" && game.phase === "paused")
        game.phase = "playing"
}

/** An action let go. */
export function release(game, action) {
    const h = game.hero
    if (action in h.held)
        h.held[action] = false
}

// ── What moves under Tam ────────────────────────────────────────────────────────────────────────────────────────────

/** A moving platform set where its count says: there and back, at its speed. */
function carryAlong(p) {
    const half = p.period / 2
    const along = (p.t <= half ? p.t : p.period - p.t) * PLATFORM_SPEED
    const x = p.ax + p.sx * along, y = p.ay + p.sy * along
    p.dx = x - p.x
    p.dy = y - p.y
    p.x = x
    p.y = y
}

function platforms(game) {
    const h = game.hero, map = MAPS[game.level]
    for (const p of game.platforms) {
        if (p.what === "mover") {
            p.t = (p.t + 1) % p.period
            carryAlong(p)
        } else {
            p.dx = 0
            p.dy = 0
            if (p.act === "shaking") {
                p.timer -= 1
                if (p.timer === 0) {
                    p.act = "falling"
                    p.vy = 0
                }
            } else if (p.act === "falling") {
                p.vy = Math.min(FALL_MOST, p.vy + FALLER_PULL)
                p.dy = p.vy
                p.y += p.vy
                if (p.y > (map.rows + 4) * TILE) {
                    p.act = "gone"
                    p.timer = FALLER_BACK
                    if (h.on === p.id)
                        h.on = -1
                }
            } else if (p.act === "gone") {
                p.timer -= 1
                if (p.timer === 0) {
                    p.act = "still"
                    p.y = p.ay
                    p.vy = 0
                }
            }
        }
        if (h.on === p.id) {
            h.y = p.y
            if (p.dx !== 0) {
                h.x += p.dx
                stopAtWalls(game, h, p.dx)
            }
        }
    }
}

/** A body stopped at the side of what it moved into, moving by `by` along x. */
function stopAtWalls(game, h, by) {
    const top = Math.floor((h.y - HERO_H) / TILE), bottom = Math.floor((h.y - 1) / TILE)
    const side = by > 0 ? Math.floor((h.x + HERO_W) / TILE) : Math.floor((h.x - HERO_W) / TILE)
    for (let r = top; r <= bottom; r++) {
        if (solidAt(game, side, r)) {
            h.x = by > 0 ? side * TILE - HERO_W : (side + 1) * TILE + HERO_W
            return true
        }
    }
    return false
}

// ── Tam ─────────────────────────────────────────────────────────────────────────────────────────────────────────────

function gainNote(game, x, y) {
    game.notes += 1
    game.score += NOTE_WORTH
    game.toLife += 1
    game.noteRun = game.steps - game.lastNote <= NOTE_CHAIN ? game.noteRun + 1 : 0
    game.lastNote = game.steps
    say(game, "note", x, y, { pitch: game.noteRun % 8 })
    if (game.toLife >= NOTES_FOR_LIFE) {
        game.toLife -= NOTES_FOR_LIFE
        game.lives += 1
        say(game, "life", x, y)
    }
}

function pickNotesAt(game, c, r) {
    const map = MAPS[game.level], key = r * map.cols + c
    const note = map.noteAt[key]
    if (note !== undefined && game.got[note] === 0) {
        game.got[note] = 1
        gainNote(game, (c + 0.5) * TILE, (r + 0.5) * TILE)
    }
    const bell = map.silverAt[key]
    if (bell !== undefined && game.silverGot[bell] === 0) {
        game.silverGot[bell] = 1
        game.silver += 1
        game.score += SILVER_WORTH
        say(game, "silver", (c + 0.5) * TILE, (r + 0.5) * TILE, { which: bell })
    }
}

/** A block struck from under. It may give, or break; what stands on it falls off, and a note over it comes down. */
function bump(game, c, r) {
    const map = MAPS[game.level], h = game.hero, key = r * map.cols + c, tile = tileAt(game, c, r)
    const x = (c + 0.5) * TILE, y = r * TILE
    if (tile === "B") {
        if (h.form !== SMALL) {
            game.changed[key] = "."
            game.score += BRICK_WORTH
            say(game, "break", x, y + TILE / 2)
        } else {
            say(game, "bump", x, y, { c: c, r: r })
        }
    } else if (tile === "Q") {
        game.changed[key] = "U"
        gainNote(game, x, y)
        say(game, "bump", x, y, { c: c, r: r, gave: true })
    } else if (tile === "R") {
        if (game.rich[key] === undefined)
            game.rich[key] = between(game.random, 4, 7)
        game.rich[key] -= 1
        gainNote(game, x, y)
        say(game, "bump", x, y, { c: c, r: r, gave: true })
        if (game.rich[key] === 0)
            game.changed[key] = "U"
    } else if (tile === "P" || tile === "L") {
        game.changed[key] = "U"
        const what = tile === "L" ? "life" : h.form === SMALL ? "brass" : "kite"
        game.items.push({ id: game.made, what: what, x: x, y: y, vx: 0, vy: 0, rising: 24, face: h.x <= x ? 1 : -1 })
        game.made += 1
        say(game, "item", x, y, { c: c, r: r })
    } else {
        say(game, "knock", x, y)
        return
    }
    for (const e of game.enemies.slice())
        if (e.kind !== MUFFLE && e.kind !== ICICLE && e.ground && Math.abs(e.y - y) < 2 && Math.abs(e.x - x) < TILE * 0.75)
            fell(game, e, 0)
    pickNotesAt(game, c, r - 1)
}

/** Something ended: it scores, more for each in one bounce. */
function fell(game, e, chain) {
    const kind = KINDS[e.kind]
    const worth = Math.min(STOMP_MOST, kind.worth * (chain >= 4 ? 16 : chain === 3 ? 8 : chain === 2 ? 4 : chain === 1 ? 2 : 1))
    game.score += e.kind === MUFFLE ? kind.worth : worth
    game.kills += 1
    game.enemies.splice(game.enemies.indexOf(e), 1)
    say(game, "kill", e.x, e.y - kind.h / 2, { kind: e.kind, worth: e.kind === MUFFLE ? kind.worth : worth, face: e.face })
}

function hurt(game) {
    const h = game.hero
    if (h.hurt > 0 || h.dying > 0 || game.clearing > 0)
        return
    if (h.form !== SMALL) {
        h.form = SMALL
        h.hurt = HURT_HOLD
        h.slam = 0
        say(game, "shrink", h.x, h.y - HERO_H / 2)
    } else {
        die(game)
    }
}

function die(game) {
    const h = game.hero
    if (h.dying > 0)
        return
    h.dying = DYING_STEPS
    h.form = SMALL
    h.vx = 0
    h.vy = 0
    h.slam = 0
    h.on = -1
    game.falls += 1
    say(game, "die", h.x, h.y - HERO_H / 2)
}

/** Waking again at the last mid-way bell, or the level's start, with its clock whole and everything back in its place. */
function wake(game) {
    const map = MAPS[game.level], held = game.hero.held
    const at = game.check >= 0 ? map.checks[game.check] : map.start
    game.hero = newHero(at[0], at[1])
    game.hero.held = held
    game.time = map.seconds * 60
    stock(game)
    say(game, "wake", game.hero.x, game.hero.y)
}

/** The hand bell rung: what is near is stunned, a hush block near wakes, and a wave Old Muffle sent goes out. */
function ring(game) {
    const h = game.hero, map = MAPS[game.level]
    const cx = h.x, cy = h.y - HERO_H / 2, reach = RING_REACH * RING_REACH
    h.ringing = RING_STEPS
    h.ringCool = RING_COOL
    say(game, "ring", cx, cy)
    const c0 = Math.floor((cx - RING_REACH) / TILE), c1 = Math.floor((cx + RING_REACH) / TILE)
    const r0 = Math.floor((cy - RING_REACH) / TILE), r1 = Math.floor((cy + RING_REACH) / TILE)
    for (let r = r0; r <= r1; r++) {
        for (let c = c0; c <= c1; c++) {
            if (tileAt(game, c, r) !== "H")
                continue
            const dx = (c + 0.5) * TILE - cx, dy = (r + 0.5) * TILE - cy
            if (dx * dx + dy * dy > reach)
                continue
            // Not one Tam is inside: it wakes around nobody.
            const inside = (c + 1) * TILE > h.x - HERO_W && c * TILE < h.x + HERO_W && (r + 1) * TILE > h.y - HERO_H && r * TILE < h.y
            if (!inside)
                game.awake[r * map.cols + c] = HUSH_STEPS
        }
    }
    for (const e of game.enemies) {
        const dx = e.x - cx, dy = e.y - KINDS[e.kind].h / 2 - cy
        if (dx * dx + dy * dy > reach || e.kind === ICICLE)
            continue
        if (e.kind !== MUFFLE) {
            e.stun = STUN_STEPS
        } else if (e.deaf === 0 && e.act !== "reeling") {
            e.stun = MUFFLE_STUN
            e.deaf = MUFFLE_DEAF
            say(game, "muffled", e.x, e.y - KINDS[e.kind].h)
        }
    }
    game.shots = game.shots.filter((s) => {
        const dx = s.x - cx, dy = s.y - cy
        return s.what !== "wave" || dx * dx + dy * dy > reach
    })
}

function accelerate(h, want, ice) {
    const max = h.held.run ? RUN : WALK
    h.skid = false
    if (want !== 0) {
        const along = want * h.vx
        if (along < 0) {
            h.vx += want * (h.ground ? (ice ? ICE_SKID : SKID) : AIR_TURN)
            h.skid = h.ground
        } else if (along < max) {
            h.vx += want * (h.ground ? (ice ? ICE_ACCEL : h.held.run ? RUN_ACCEL : ACCEL) : AIR_ACCEL)
            if (want * h.vx > max)
                h.vx = want * max
        } else if (h.ground) {
            // Let go of running, it eases back to a walk.
            h.vx -= want * Math.min(along - max, ice ? ICE_FRICTION : FRICTION)
        }
        h.facing = want
    } else if (h.ground) {
        const brake = ice ? ICE_FRICTION : FRICTION
        h.vx = h.vx > brake ? h.vx - brake : h.vx < -brake ? h.vx + brake : 0
    }
}

/** Along x, stopped by walls. */
function moveAcross(game, h) {
    if (h.vx === 0)
        return
    h.x += h.vx
    if (stopAtWalls(game, h, h.vx))
        h.vx = 0
}

/** Along y: a head stopped by what it strikes, or slipping past a corner; feet stopped by what they land on. */
function moveUpDown(game, h) {
    const map = MAPS[game.level]
    h.y += h.vy
    if (h.vy < 0) {
        const r = Math.floor((h.y - HERO_H) / TILE)
        const c0 = Math.floor((h.x - HERO_W + 1) / TILE), c1 = Math.floor((h.x + HERO_W - 1) / TILE)
        const left = solidAt(game, c0, r), right = solidAt(game, c1, r)
        if (!left && !right)
            return
        if (c0 !== c1 && left !== right) {
            // Only the corner of the block: a head this close slips past, and flies on.
            const slip = left ? (c0 + 1) * TILE - (h.x - HERO_W) : h.x + HERO_W - c1 * TILE
            if (slip <= CORNER) {
                h.x += left ? slip : -slip
                return
            }
        }
        // The block nearest the middle of the head takes the blow.
        const middle = Math.floor(h.x / TILE)
        const struck = solidAt(game, middle, r) ? middle : left ? c0 : c1
        h.y = (r + 1) * TILE + HERO_H
        h.vy = 0
        h.lifted = false
        bump(game, struck, r)
        return
    }
    const r = Math.floor((h.y - 0.001) / TILE)
    const c0 = Math.floor((h.x - HERO_W + 1) / TILE), c1 = Math.floor((h.x + HERO_W - 1) / TILE)
    if (Math.floor((h.before - 0.001) / TILE) < r) {
        let landed = false
        for (let c = c0; c <= c1; c++)
            landed = landed || standsOn(game, c, r)
        if (landed && h.slam < 0) {
            // A slam goes through brick, and on down.
            let broke = false
            for (let c = c0; c <= c1; c++) {
                if (tileAt(game, c, r) === "B") {
                    game.changed[r * map.cols + c] = "."
                    game.score += BRICK_WORTH
                    say(game, "break", (c + 0.5) * TILE, (r + 0.5) * TILE)
                    broke = true
                }
            }
            landed = false
            for (let c = c0; c <= c1; c++)
                landed = landed || standsOn(game, c, r)
            if (broke && !landed)
                return
        }
        if (landed) {
            h.y = r * TILE
            land(game, h)
            return
        }
    }
    for (const p of game.platforms) {
        if (p.act === "gone" || h.x + HERO_W <= p.x || h.x - HERO_W >= p.x + p.w)
            continue
        if (h.before <= p.y + 3 && h.y >= p.y) {
            h.y = p.y
            h.on = p.id
            if (p.what === "faller" && p.act === "still") {
                p.act = "shaking"
                p.timer = FALLER_WAIT
            }
            land(game, h)
            return
        }
    }
}

function land(game, h) {
    const speed = h.vy
    h.vy = 0
    h.ground = true
    h.lifted = false
    h.gliding = false
    h.chain = 0
    if (h.slam < 0) {
        h.slam = 0
        h.vy = -SLAM_BOUNCE
        h.ground = false
        say(game, "slam", h.x, h.y)
        for (const e of game.enemies.slice()) {
            if (Math.abs(e.x - h.x) > SLAM_REACH + KINDS[e.kind].w || Math.abs(e.y - h.y) > TILE)
                continue
            if (e.kind === MUFFLE)
                e.stun = Math.max(e.stun, MUFFLE_STUN / 2)
            else if (e.kind !== ICICLE)
                fell(game, e, 0)
        }
    } else if (speed > 3) {
        say(game, "land", h.x, h.y, { hard: speed })
    }
}

function hero(game) {
    const h = game.hero, map = MAPS[game.level]
    if (h.hurt > 0)
        h.hurt -= 1
    if (h.ringCool > 0)
        h.ringCool -= 1
    if (h.ringing > 0)
        h.ringing -= 1
    if (h.hold > 0) {
        h.hold -= 1
        noAsks(h)
        return
    }
    if (h.ask.ring && h.ringCool === 0)
        ring(game)
    if (h.ask.down && !h.ground && h.slam === 0) {
        h.slam = SLAM_HOLD
        h.vx = 0
        h.vy = 0
        h.gliding = false
        h.on = -1
        say(game, "hover", h.x, h.y)
    }
    if (h.ask.up && h.ground) {
        for (const door of map.doors) {
            const here = [door.a, door.b].find((d) => Math.abs((d[0] + 0.5) * TILE - h.x) < TILE * 0.8 && d[1] === Math.floor((h.y - 1) / TILE))
            if (here) {
                const there = here === door.a ? door.b : door.a
                h.x = (there[0] + 0.5) * TILE
                h.y = (there[1] + 1) * TILE
                h.vx = 0
                h.on = -1
                h.hold = 24
                say(game, "door", h.x, h.y)
                noAsks(h)
                return
            }
        }
    }
    h.ask.ring = false
    h.ask.up = false
    h.ask.down = false

    const below = Math.floor((h.y + 1) / TILE)
    const ice = h.ground && (tileAt(game, Math.floor(h.x / TILE), below) === "I")
    const wasGround = h.ground
    if (h.slam > 0) {
        h.slam -= 1
        if (h.slam === 0) {
            h.slam = -1
            say(game, "drop", h.x, h.y)
        }
    } else if (h.slam < 0) {
        h.vx = 0
        h.vy = SLAM_FALL
    } else {
        const want = (h.held.right ? 1 : 0) - (h.held.left ? 1 : 0)
        accelerate(h, want, ice)
        if (h.buffer > 0) {
            if (h.ground || h.coyote > 0) {
                h.vy = -(JUMP + JUMP_RUN * Math.abs(h.vx))
                h.ground = false
                h.coyote = 0
                h.buffer = 0
                h.on = -1
                say(game, "jump", h.x, h.y)
            } else {
                h.buffer -= 1
            }
        }
        const pull = h.vy < 0 && (h.held.jump || h.lifted) ? RISE_PULL : FALL_PULL
        h.vy = Math.min(FALL_MOST, h.vy + pull)
        h.gliding = h.form === KITE && !h.ground && h.vy > GLIDE_FALL && h.held.jump
        if (h.gliding)
            h.vy = GLIDE_FALL
    }
    h.before = h.y
    moveAcross(game, h)
    h.ground = false
    const on = h.on
    h.on = -1
    if (h.slam <= 0)
        moveUpDown(game, h)
    if (h.on !== on && on >= 0 && h.vy >= 0 && h.y > game.platforms[on].y + 3)
        h.on = -1
    if (h.ground)
        h.coyote = COYOTE
    else if (wasGround && h.vy >= 0)
        h.coyote = COYOTE - 1
    else if (h.coyote > 0)
        h.coyote -= 1

    if (h.y > (map.rows + 3) * TILE) {
        die(game)
        return
    }
    touching(game, h)
}

/** What Tam's body overlaps at rest: thorns, notes, bells, springs. */
function touching(game, h) {
    const map = MAPS[game.level]
    const c0 = Math.floor((h.x - HERO_W + 1) / TILE), c1 = Math.floor((h.x + HERO_W - 1) / TILE)
    const r0 = Math.floor((h.y - HERO_H) / TILE), r1 = Math.floor((h.y - 1) / TILE)
    for (let r = r0; r <= r1; r++) {
        for (let c = c0; c <= c1; c++) {
            if (c < 0 || c >= map.cols || r < 0 || r >= map.rows)
                continue
            pickNotesAt(game, c, r)
            // Thorns take the tile's lower half.
            if (tileAt(game, c, r) === "T" && h.y > (r + 0.45) * TILE)
                hurt(game)
        }
    }
    for (const [c, r] of map.springs) {
        if (h.vy >= 0 && h.y >= (r + 0.5) * TILE && h.y <= (r + 1) * TILE + 1 && Math.abs((c + 0.5) * TILE - h.x) < TILE / 2 + HERO_W - 2) {
            h.y = (r + 0.5) * TILE
            h.vy = -SPRING
            h.lifted = true
            h.ground = false
            h.on = -1
            h.slam = 0
            h.coyote = 0
            say(game, "spring", (c + 0.5) * TILE, (r + 1) * TILE, { c: c, r: r })
        }
    }
    map.checks.forEach(([c, r], n) => {
        if (n > game.check && Math.abs((c + 0.5) * TILE - h.x) < TILE * 0.75 && h.y > (r - 2) * TILE && h.y <= (r + 2) * TILE) {
            game.check = n
            say(game, "check", (c + 0.5) * TILE, (r + 1) * TILE, { which: n })
        }
    })
    // Only at the bell itself: a level's secret room may lie beyond it.
    if (map.goal && h.x + HERO_W >= (map.goal.c + 0.3) * TILE && h.x - HERO_W <= (map.goal.c + 1) * TILE && game.clearing === 0) {
        const high = Math.max(0, Math.min(7, Math.floor((map.goal.floor - h.y) / TILE)))
        const bonus = 100 + 200 * high
        game.score += bonus
        say(game, "goal", (map.goal.c + 0.5) * TILE, h.y, { bonus: bonus, high: high })
        clear(game)
    }
}

/** A level done: what its clock has left scores, and Tam rings it out. */
function clear(game) {
    const h = game.hero
    game.clearing = CLEARING_STEPS
    game.bonus = Math.floor(game.time / 60) * SECOND_WORTH
    game.score += game.bonus
    h.vx = 0
    h.vy = 0
    h.skid = false
    h.slam = 0
    h.gliding = false
    h.on = -1
}

function clearing(game) {
    const h = game.hero
    // Tam comes down to the ground, and stands there.
    const r = Math.floor((h.y + 1) / TILE)
    if (h.y < (MAPS[game.level].rows + 3) * TILE && !footing(game, h.x, h.y, HERO_W)) {
        h.y += 3
        if (footing(game, h.x, h.y, HERO_W) && Math.floor((h.y + 1) / TILE) === r + 1)
            h.y = (r + 1) * TILE
    }
    h.ground = true
    game.clearing -= 1
    if (game.clearing > 0)
        return
    game.levels += 1
    if (game.level + 1 >= MAPS.length) {
        game.won = true
        game.score += game.lives * LIFE_WORTH
        finish(game)
        say(game, "won", h.x, h.y)
    } else {
        enter(game, game.level + 1)
        say(game, "level", game.hero.x, game.hero.y, { level: game.level })
    }
}

function finish(game) {
    game.phase = "over"
}

// ── What walks ──────────────────────────────────────────────────────────────────────────────────────────────────────

/** Along x, turning at a wall: true if it turned. */
function walkOn(game, e, w, h) {
    e.x += e.vx
    const side = Math.floor((e.vx > 0 ? e.x + w : e.x - w) / TILE)
    for (let r = Math.floor((e.y - h) / TILE); r <= Math.floor((e.y - 1) / TILE); r++) {
        if (solidAt(game, side, r)) {
            e.x = e.vx > 0 ? side * TILE - w : (side + 1) * TILE + w
            return true
        }
    }
    return false
}

/** Down, onto what it lands on. */
function fallOn(game, e, w, pull) {
    const before = e.y
    e.vy = Math.min(FALL_MOST, e.vy + pull)
    e.y += e.vy
    e.ground = false
    if (e.vy < 0) {
        const r = Math.floor((e.y - KINDS[e.kind].h) / TILE)
        for (let c = Math.floor((e.x - w + 1) / TILE); c <= Math.floor((e.x + w - 1) / TILE); c++) {
            if (solidAt(game, c, r)) {
                e.y = (r + 1) * TILE + KINDS[e.kind].h
                e.vy = 0
                return
            }
        }
        return
    }
    const r = Math.floor((e.y - 0.001) / TILE)
    if (Math.floor((before - 0.001) / TILE) >= r)
        return
    for (let c = Math.floor((e.x - w + 1) / TILE); c <= Math.floor((e.x + w - 1) / TILE); c++) {
        if (standsOn(game, c, r)) {
            e.y = r * TILE
            e.vy = 0
            e.ground = true
            return
        }
    }
}

function walker(game, e, kind, careful) {
    if (e.stun > 0) {
        fallOn(game, e, kind.w, FALL_PULL)
        return
    }
    const speed = kind.speed
    e.vx = e.face * speed
    const wall = walkOn(game, e, kind.w, kind.h)
    fallOn(game, e, kind.w, FALL_PULL)
    if (wall)
        e.face = -e.face
    else if (careful && e.ground && !footing(game, e.x + e.face * kind.w, e.y, 1))
        e.face = -e.face
}

/** A flit goes back and forth along its beat, bobbing as a parabola does. */
function flit(game, e, kind) {
    if (e.stun > 0)
        return
    const t = (game.steps + e.phase) % 240
    const along = t < 120 ? t : 240 - t
    const x = e.homeX + (along - 60) * kind.speed
    e.face = x >= e.x ? 1 : -1
    e.x = x
    const u = ((game.steps + e.phase) % 80) / 40 - 1
    e.y = e.homeY + 14 * u * u - 7
}

function boing(game, e, kind, dx) {
    if (e.stun > 0) {
        fallOn(game, e, kind.w, FALL_PULL)
        return
    }
    if (e.ground) {
        e.vx = 0
        e.timer -= 1
        if (e.timer <= 0 && Math.abs(dx) < NOTICE) {
            e.face = dx > 0 ? 1 : -1
            e.vx = e.face * kind.speed
            e.vy = -7.5
            e.ground = false
            e.timer = 50 + e.phase / 4
            say(game, "boing", e.x, e.y)
        }
    }
    if (e.vx !== 0 && walkOn(game, e, kind.w, kind.h))
        e.vx = -e.vx
    fallOn(game, e, kind.w, FALL_PULL)
}

function gourd(game, e, kind, dx, dy) {
    fallOn(game, e, kind.w, FALL_PULL)
    if (e.stun > 0)
        return
    e.face = dx > 0 ? 1 : -1
    e.timer -= 1
    if (e.timer <= 0) {
        e.timer = 110 + e.phase / 3
        if (Math.abs(dx) < NOTICE && Math.abs(dy) < 5 * TILE) {
            game.shots.push({ id: game.made, what: "seed", x: e.x + e.face * kind.w, y: e.y - kind.h * 0.6, vx: e.face * SEED_SPEED, left: SEED_STEPS })
            game.made += 1
            say(game, "spit", e.x, e.y - kind.h / 2)
        }
    }
}

function icicle(game, e, kind, dx, dy) {
    if (e.act === "hang") {
        if (Math.abs(dx) < 44 && dy > 0 && dy < 9 * TILE) {
            e.act = "shake"
            e.timer = 26
            say(game, "creak", e.x, e.y)
        }
    } else if (e.act === "shake") {
        e.timer -= 1
        if (e.timer === 0)
            e.act = "fall"
    } else {
        e.vy = Math.min(FALL_MOST, e.vy + FALL_PULL)
        e.y += e.vy
        const r = Math.floor((e.y - 1) / TILE)
        if (solidAt(game, Math.floor(e.x / TILE), r)) {
            say(game, "shatter", e.x, r * TILE)
            game.enemies.splice(game.enemies.indexOf(e), 1)
        }
    }
}

function muffle(game, e, kind, dx) {
    if (e.deaf > 0)
        e.deaf -= 1
    if (e.stun > 0) {
        fallOn(game, e, kind.w, FALL_PULL)
        return
    }
    const hurried = 1 + (e.most - e.hits) * 0.22
    if (e.act === "prowl") {
        e.face = dx > 0 ? 1 : -1
        e.vx = e.face * kind.speed * hurried
        if (walkOn(game, e, kind.w, kind.h))
            e.vx = 0
        fallOn(game, e, kind.w, FALL_PULL)
        e.timer -= 1
        if (e.timer <= 0 && e.ground) {
            e.act = "air"
            e.vy = -LEAP
            e.vx = Math.max(-4, Math.min(4, dx / 44))
            e.ground = false
            say(game, "leap", e.x, e.y)
        }
    } else if (e.act === "air") {
        if (walkOn(game, e, kind.w, kind.h))
            e.vx = 0
        fallOn(game, e, kind.w, RISE_PULL + 0.1)
        if (e.ground) {
            e.act = "open"
            e.timer = OPEN_STEPS
            say(game, "thump", e.x, e.y)
            for (const way of [-1, 1]) {
                game.shots.push({ id: game.made, what: "wave", x: e.x + way * kind.w, y: e.y - 10, vx: way * WAVE_SPEED * hurried, left: WAVE_STEPS })
                game.made += 1
            }
        }
    } else {
        fallOn(game, e, kind.w, FALL_PULL)
        e.timer -= 1
        if (e.timer <= 0) {
            e.act = "prowl"
            e.timer = Math.max(70, PROWL_STEPS - (e.most - e.hits) * 15)
        }
    }
}

/** Whether Old Muffle can be stomped now: open, or rung. */
export function muffleOpen(e) {
    return e.stun > 0 || e.act === "open"
}

function enemies(game) {
    const h = game.hero, map = MAPS[game.level]
    for (const e of game.enemies.slice()) {
        const kind = KINDS[e.kind], dx = h.x - e.x, dy = h.y - e.y
        if (Math.abs(dx) > ACTIVE_REACH || Math.abs(dy) > ACTIVE_REACH)
            continue
        if (e.stun > 0)
            e.stun -= 1
        if (e.kind === MUMBLE)
            walker(game, e, kind, false)
        else if (e.kind === HUSHLING || e.kind === THISTLE)
            walker(game, e, kind, true)
        else if (e.kind === FLIT)
            flit(game, e, kind)
        else if (e.kind === BOING)
            boing(game, e, kind, dx)
        else if (e.kind === GOURD)
            gourd(game, e, kind, dx, dy)
        else if (e.kind === ICICLE)
            icicle(game, e, kind, dx, dy)
        else
            muffle(game, e, kind, dx)
        if (e.y > (map.rows + 3) * TILE) {
            game.enemies.splice(game.enemies.indexOf(e), 1)
            continue
        }
        if (game.enemies.includes(e))
            meet(game, e, kind)
        if (h.dying > 0 || game.clearing > 0)
            return
    }
}

/** Tam and a thing meet: from above and falling, a stomp; else what it does to those it touches. */
function meet(game, e, kind) {
    const h = game.hero
    if (h.x + HERO_W <= e.x - kind.w || h.x - HERO_W >= e.x + kind.w || h.y <= e.y - kind.h || h.y - HERO_H >= e.y)
        return
    if (e.act === "reeling")
        return
    if (e.kind === ICICLE) {
        if (e.act === "fall")
            hurt(game)
        return
    }
    const fromAbove = (h.vy > 0 || h.slam !== 0) && h.before <= e.y - kind.h + 12
    if (fromAbove) {
        if (e.kind === MUFFLE) {
            if (muffleOpen(e)) {
                hit(game, e)
                rebound(h)
            } else {
                hurt(game)
            }
            return
        }
        if (h.slam !== 0 || e.kind !== THISTLE || e.stun > 0) {
            h.chain += 1
            fell(game, e, h.chain - 1)
            rebound(h)
            return
        }
    }
    if (e.stun > 0)
        return
    hurt(game)
}

function rebound(h) {
    h.vy = -(h.held.jump ? BOUNCE_HELD : BOUNCE)
    h.lifted = h.held.jump
    h.slam = 0
    h.ground = false
    h.coyote = 0
}

function hit(game, e) {
    e.hits -= 1
    e.stun = 0
    say(game, "struck", e.x, e.y - KINDS[e.kind].h, { left: e.hits })
    if (e.hits <= 0) {
        fell(game, e, 0)
        game.shots = []
        clear(game)
        return
    }
    e.act = "reeling"
    e.timer = REEL_STEPS
}

function reels(game) {
    for (const e of game.enemies) {
        if (e.act === "reeling") {
            e.timer -= 1
            if (e.timer <= 0) {
                e.act = "prowl"
                e.timer = PROWL_STEPS / 2
                e.deaf = 0
            }
        }
    }
}

function shots(game) {
    const h = game.hero
    game.shots = game.shots.filter((s) => {
        s.x += s.vx
        s.left -= 1
        if (s.left <= 0 || solidAt(game, Math.floor(s.x / TILE), Math.floor(s.y / TILE)))
            return false
        if (h.x + HERO_W > s.x - 7 && h.x - HERO_W < s.x + 7 && h.y > s.y - 7 && h.y - HERO_H < s.y + 7) {
            hurt(game)
            return false
        }
        return true
    })
}

function items(game) {
    const h = game.hero
    game.items = game.items.filter((item) => {
        if (item.rising > 0) {
            item.rising -= 1
            item.y -= TILE / 24
            return true
        }
        if (item.what === "kite") {
            // It rides the air, and comes slowly down.
            const t = (game.steps + item.id * 37) % 120
            item.vx = (t < 60 ? 1 : -1) * 0.8
            item.x += item.vx
            item.y += 0.25
        } else {
            item.vx = item.face * (item.what === "life" ? 1.6 : 1.2)
            item.x += item.vx
            const side = Math.floor((item.x + item.face * 10) / TILE)
            if (solidAt(game, side, Math.floor((item.y - 8) / TILE)))
                item.face = -item.face
            item.vy = Math.min(FALL_MOST, item.vy + FALL_PULL)
            const before = item.y
            item.y += item.vy
            const r = Math.floor((item.y - 0.001) / TILE)
            if (Math.floor((before - 0.001) / TILE) < r && standsOn(game, Math.floor(item.x / TILE), r)) {
                item.y = r * TILE
                item.vy = 0
            }
        }
        if (item.y > (MAPS[game.level].rows + 3) * TILE)
            return false
        if (h.x + HERO_W > item.x - 12 && h.x - HERO_W < item.x + 12 && h.y > item.y - 24 && h.y - HERO_H < item.y) {
            if (item.what === "life") {
                game.lives += 1
                say(game, "life", item.x, item.y)
            } else {
                if (item.what === "kite" || h.form === SMALL)
                    h.form = item.what === "kite" ? KITE : BRASS
                game.score += ITEM_WORTH
                say(game, "power", item.x, item.y, { what: item.what })
            }
            return false
        }
        return true
    })
}

/** The hush blocks going back to sleep, and heard doing it a moment before. */
function hush(game) {
    for (const key in game.awake) {
        game.awake[key] -= 1
        if (game.awake[key] <= 0)
            delete game.awake[key]
    }
}

/** One step of the game. */
export function step(game) {
    game.said = []
    if (game.phase !== "playing")
        return
    game.steps += 1
    if (game.steps >= RUN_STEPS) {
        finish(game)
        return
    }
    if (game.clearing > 0) {
        clearing(game)
        return
    }
    const h = game.hero
    if (h.dying > 0) {
        h.dying -= 1
        if (h.dying === 0) {
            game.lives -= 1
            if (game.lives <= 0)
                finish(game)
            else
                wake(game)
        }
        return
    }
    game.time -= 1
    if (game.time <= 0) {
        say(game, "late", h.x, h.y)
        die(game)
        return
    }
    hush(game)
    reels(game)
    platforms(game)
    hero(game)
    if (h.dying > 0 || game.clearing > 0)
        return
    enemies(game)
    if (h.dying > 0 || game.clearing > 0)
        return
    shots(game)
    if (h.dying > 0 || game.clearing > 0)
        return
    items(game)
}

/** What the run came to. */
export function outcome(game) {
    return {
        score: game.score,
        notes: game.notes,
        silver: game.silver,
        kills: game.kills,
        falls: game.falls,
        lives: game.lives,
        levels: game.levels,
        seconds: Math.floor(game.steps / 60),
        won: game.won,
        over: game.phase === "over",
    }
}

/** A QQ run played again, in Node or anywhere else that runs JavaScript: its outcome. */
export function replay(run) {
    if (!run || run.qqRun !== 1 || !Number.isInteger(run.seed) || !Number.isInteger(run.ticks) || run.ticks < 0)
        throw new Error("This replays QQ runs of format 1.")
    const edges = new Map((run.edges || []).map(([tick, list]) => [tick, list]))
    const clicks = new Map((run.clicks || []).map(([tick, list]) => [tick, list]))
    const game = create(run.seed)
    for (let tick = 0; tick < run.ticks; tick++) {
        for (const button of clicks.get(tick) || [])
            click(game, button)
        for (const [what, action] of edges.get(tick) || []) {
            if (what === "pressed")
                press(game, action)
            else if (what === "released")
                release(game, action)
        }
        step(game)
    }
    return outcome(game)
}
