const ENEMY_MARKS = { a: MUMBLE, b: HUSHLING, c: THISTLE, d: FLIT, e: BOING, f: GOURD, g: ICICLE, X: MUFFLE }

/** A level read: its tiles, with what stands in them lifted out into lists. */
function read(level) {
    const out = { name: level.name, world: level.world, seconds: level.seconds, rows: level.rows.length, cols: level.rows[0].length,
                  tiles: [], notes: [], noteAt: {}, silver: [], silverAt: {}, springs: [], checks: [], goal: null, start: null,
                  spawns: [], platforms: [], doors: [] }
    const key = (c, r) => r * out.cols + c
    const ins = [], outs = []
    level.rows.forEach((row, r) => {
        let tiles = ""
        for (let c = 0; c < row.length; c++) {
            const mark = row.charAt(c)
            let tile = "."
            if ("#I=BQRPLHT".includes(mark))
                tile = mark
            else if (mark === "o") {
                out.noteAt[key(c, r)] = out.notes.length
                out.notes.push([c, r])
            } else if (mark === "S") {
                out.silverAt[key(c, r)] = out.silver.length
                out.silver.push([c, r])
            } else if (mark === "J")
                out.springs.push([c, r])
            else if (mark === "K")
                out.checks.push([c, r])
            else if (mark === "G")
                out.goal = { c: c, r: r }
            else if (mark === "@")
                out.start = [c, r]
            else if (mark in ENEMY_MARKS)
                out.spawns.push({ kind: ENEMY_MARKS[mark], c: c, r: r })
            else if (mark === "M")
                out.platforms.push({ what: "mover", c: c, r: r, w: 3, to: [row.indexOf("!", c) - c, 0] })
            else if (mark === "V") {
                let to = -1
                for (let n = r + 1; n < level.rows.length && to < 0; n++)
                    if (level.rows[n].charAt(c) === "!")
                        to = n - r
                for (let n = r - 1; n >= 0 && to < 0; n--)
                    if (level.rows[n].charAt(c) === "!")
                        to = n - r
                out.platforms.push({ what: "mover", c: c, r: r, w: 3, to: [0, to] })
            } else if (mark === "F")
                out.platforms.push({ what: "faller", c: c, r: r, w: 2, to: [0, 0] })
            else if (mark === "D")
                ins.push([c, r])
            else if (mark === "E")
                outs.push([c, r])
            tiles += tile
        }
        out.tiles.push(tiles)
    })
    ins.forEach((door, n) => out.doors.push({ a: door, b: outs[n] }))
    out.checks.sort((a, b) => a[0] - b[0])
    if (out.goal) {
        let floor = out.goal.r
        while (floor < out.rows && !"#I".includes(out.tiles[floor].charAt(out.goal.c)))
            floor += 1
        out.goal.floor = floor * TILE
    }
    return out
}

