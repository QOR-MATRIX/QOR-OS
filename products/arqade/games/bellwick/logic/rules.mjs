// Bellwick's rules (QOR OS's QOR-0017): a platformer on islands in the sky. The Hush has muffled the bells that hold the
// isles up. Tam, the smallest ringer in Bellwick, runs and jumps across eight levels in four regions and rings the Great Bell
// at the end of each, stomping what walks, ringing a hand bell to stun it and to wake the hush blocks, and slamming down
// through brick. Old Muffle waits at the top of the Belfry and again in the Last Belfry; ended there, the run is won. Spending
// every life ends it, and so does the clock.
//
// The rules live here alone, so the game and ARQADE's service run the same ones (Demiurge's ADR-102): the QQ game's logic
// (logic/bellwick.qml) hands each event to them and draws what they say, and the service replays a run, the very file
// QQ records (`qqRun` 1), with `replay` below, to reach the outcome the player's game reached. Nothing here uses QQ or
// Qt, and nothing here comes from outside this package (ADR-087 decision 2).
//
// They keep to what every machine computes alike: adding, subtracting, multiplying, dividing, `Math.floor`, whole
// numbers, and `Math.sqrt`, which ECMAScript specifies exactly (IEEE 754's correctly rounded square root). No sine,
// cosine, power or logarithm decides anything: a flit's bob is a parabola. Random numbers come from the run's seed through
// xoshiro128**, its state filled by splitmix32, and change only when things do: what a level's layout says is the same for
// every seed. A level is measured in tiles of 32 units, with y running down, and a body by its feet.
//
// A game is a plain object; each function takes it and changes it:
//   create(seed)           a game on its title, from a seed (a whole number)
//   click(game, button)    a screen button: "Play", "Play again", "Resume"
//   press(game, action)    an action pressed: "left", "right" held to move, "run" held to go faster, "jump" (held, it goes
//                          higher), "ring", "down" (in the air, a slam), "up" (at a door, through it), "pause"
//   release(game, action)  an action let go
//   step(game)             one step of 1/60 s, which moves only while the game plays
//   outcome(game)          { score, notes, silver, kills, falls, lives, levels, seconds, won, over }
//   replay(run)            a QQ run (seed, ticks, edges, clicks) played again: its outcome

